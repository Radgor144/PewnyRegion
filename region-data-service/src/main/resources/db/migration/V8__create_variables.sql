
CREATE TABLE variables
(
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_name   VARCHAR(255) NOT NULL UNIQUE,
    category   VARCHAR(50) NOT NULL,
    direction  VARCHAR(20) NOT NULL,
    per_capita BOOLEAN NOT NULL DEFAULT FALSE,
    unit       VARCHAR(50) NOT NULL
);

INSERT INTO variables (
    id,
    api_name,
    category,
    direction,
    per_capita,
    unit
)
SELECT
    id,
    api_name,
    category,
    direction,
    per_capita,
    unit
FROM bdl_variables;

SELECT setval(
               pg_get_serial_sequence('variables', 'id'),
               COALESCE((SELECT MAX(id) FROM variables), 1),
               EXISTS (SELECT 1 FROM variables)
       );

ALTER TABLE variable_external_ids
    DROP CONSTRAINT fk_variable_external_ids_variable;

ALTER TABLE variable_external_ids
    ADD CONSTRAINT fk_variable_external_ids_variables
        FOREIGN KEY (variable_id)
            REFERENCES variables (id);
