CREATE TABLE import_jobs
(
    id          VARCHAR(36) PRIMARY KEY,
    job_type    VARCHAR(50) NOT NULL,
    provider    VARCHAR(30),
    status      VARCHAR(20) NOT NULL,
    started_at  TIMESTAMP,
    finished_at TIMESTAMP,
    message     TEXT,

    CONSTRAINT chk_import_jobs_status
        CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED'))
);


CREATE TABLE territorial_units
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teryt_code      VARCHAR(7) NOT NULL UNIQUE,
    name            VARCHAR(100) NOT NULL,
    additional_name VARCHAR(50),
    unit_level      VARCHAR(30) NOT NULL,
    rodz            VARCHAR(1),
    parent_unit_id  BIGINT REFERENCES territorial_units (id),
    source_state_at DATE,
    active          BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_territorial_units_level
        CHECK (unit_level IN ('VOIVODESHIP', 'COUNTY', 'MUNICIPALITY')),

    CONSTRAINT chk_territorial_units_teryt_code
        CHECK (
            (unit_level = 'VOIVODESHIP' AND teryt_code ~ '^[0-9]{2}$')
                OR
            (unit_level = 'COUNTY' AND teryt_code ~ '^[0-9]{4}$')
                OR
            (unit_level = 'MUNICIPALITY' AND teryt_code ~ '^[0-9]{7}$')
            )
);


CREATE TABLE variables
(
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_name   VARCHAR(255) NOT NULL UNIQUE,
    category   VARCHAR(50) NOT NULL,
    direction  VARCHAR(20) NOT NULL,
    per_capita BOOLEAN NOT NULL DEFAULT FALSE,
    unit       VARCHAR(50) NOT NULL,

    CONSTRAINT chk_variables_direction
        CHECK (direction IN ('STIMULANT', 'DESTIMULANT'))
);


CREATE TABLE territorial_unit_external_ids
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    territorial_unit_id BIGINT NOT NULL,
    provider            VARCHAR(30) NOT NULL,
    external_id         VARCHAR(100) NOT NULL,
    provider_level      VARCHAR(30),

    CONSTRAINT fk_tuei_territorial_unit
        FOREIGN KEY (territorial_unit_id)
            REFERENCES territorial_units (id),

    CONSTRAINT uq_tuei_provider_external_id
        UNIQUE (provider, external_id),

    CONSTRAINT uq_tuei_unit_provider
        UNIQUE (territorial_unit_id, provider)
);


CREATE TABLE variable_external_ids
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variable_id INTEGER NOT NULL,
    provider    VARCHAR(30) NOT NULL,
    external_id VARCHAR(100) NOT NULL,

    CONSTRAINT fk_vei_variable
        FOREIGN KEY (variable_id)
            REFERENCES variables (id),

    CONSTRAINT uq_vei_provider_external_id
        UNIQUE (provider, external_id)
);


CREATE TABLE statistical_data_records
(
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    territorial_unit_external_id_id BIGINT NOT NULL,
    variable_external_id_id         BIGINT NOT NULL,
    year                            INTEGER NOT NULL,
    value                           DOUBLE PRECISION NOT NULL,
    imported_at                     TIMESTAMP NOT NULL,
    import_job_id                   VARCHAR(36) NOT NULL,

    CONSTRAINT fk_sdr_territorial_unit_external_id
        FOREIGN KEY (territorial_unit_external_id_id)
            REFERENCES territorial_unit_external_ids (id),

    CONSTRAINT fk_sdr_variable_external_id
        FOREIGN KEY (variable_external_id_id)
            REFERENCES variable_external_ids (id),

    CONSTRAINT fk_sdr_import_job
        FOREIGN KEY (import_job_id)
            REFERENCES import_jobs (id),

    CONSTRAINT chk_sdr_year
        CHECK (year > 0),

    CONSTRAINT uq_sdr_import_record
        UNIQUE (
                territorial_unit_external_id_id,
                variable_external_id_id,
                year,
                import_job_id
            )
);


CREATE TABLE territorial_unit_variable_scores
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    territorial_unit_id BIGINT NOT NULL,
    variable_id         INTEGER NOT NULL,
    year                INTEGER NOT NULL,
    raw_value           DOUBLE PRECISION NOT NULL,
    adjusted_value      DOUBLE PRECISION NOT NULL,
    normalized_score   DOUBLE PRECISION NOT NULL,
    calculation_job_id  VARCHAR(36) NOT NULL,
    calculated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_tuvs_territorial_unit
        FOREIGN KEY (territorial_unit_id)
            REFERENCES territorial_units (id),

    CONSTRAINT fk_tuvs_variable
        FOREIGN KEY (variable_id)
            REFERENCES variables (id),

    CONSTRAINT fk_tuvs_calculation_job
        FOREIGN KEY (calculation_job_id)
            REFERENCES import_jobs (id),

    CONSTRAINT chk_tuvs_normalized_score
        CHECK (normalized_score BETWEEN 0.0 AND 1.0),

    CONSTRAINT uq_tuvs_snapshot
        UNIQUE (
                territorial_unit_id,
                variable_id,
                year,
                calculation_job_id
            )
);


CREATE UNIQUE INDEX uq_import_jobs_single_active
    ON import_jobs ((1))
    WHERE status IN ('PENDING', 'RUNNING');


CREATE INDEX idx_territorial_units_parent
    ON territorial_units (parent_unit_id);

CREATE INDEX idx_territorial_units_level_active
    ON territorial_units (unit_level, active);


CREATE INDEX idx_variable_external_ids_variable_provider
    ON variable_external_ids (variable_id, provider);


CREATE INDEX idx_statistical_data_records_import_job
    ON statistical_data_records (import_job_id);

CREATE INDEX idx_statistical_data_records_variable_year
    ON statistical_data_records (variable_external_id_id, year);

CREATE INDEX idx_statistical_data_records_latest
    ON statistical_data_records (
                                 territorial_unit_external_id_id,
                                 variable_external_id_id,
                                 year,
                                 imported_at DESC,
                                 id DESC
        );


CREATE INDEX idx_tuvs_snapshot_variable_year
    ON territorial_unit_variable_scores (
                                         calculation_job_id,
                                         variable_id,
                                         year
        );

CREATE INDEX idx_tuvs_unit_variable_year
    ON territorial_unit_variable_scores (
                                         territorial_unit_id,
                                         variable_id,
                                         year
        );
